export function getKlineDrawingToolLabel(key: string): string {
  const localeKey = key as keyof typeof KLINE_RU_DRAWING_LOCALE;
  return KLINE_RU_DRAWING_LOCALE[localeKey] ?? key;
}

export function getKlineIndicatorLabel(name: string): string {
  const key = name.toLowerCase() as keyof typeof KLINE_RU_INDICATOR_LOCALE;
  return KLINE_RU_INDICATOR_LOCALE[key] ?? name;
}

/** Русское описание без аббревиатуры: «скользящая средняя». */
export function getKlineIndicatorRuDescription(name: string): string {
  const full = getKlineIndicatorLabel(name);
  const match = full.match(/\((.+)\)$/);
  return match?.[1]?.trim() ?? "";
}

